#!/usr/bin/env python3
"""Generates Engine/SelfTest.cpp from tests/selftest.S without a cross toolchain.
Equivalent to tools/gen_selftest.sh, but assembles with keystone (pip).
Also validates the result with capstone and prints the disassembly."""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import pyasm

REPO = os.environ.get("LOP_REPO", os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(REPO, "tests", "selftest.S")
OUT = os.path.join(REPO, "Engine", "SelfTest.cpp")

def main():
    src = open(SRC).read()
    data, labels = pyasm.assemble(src)
    dis = pyasm.verify(data)
    print(f"assembled {len(data)} bytes, {len(dis)} instructions, {len(labels)} labels")

    # quick sanity: program must contain the hlt and end at it
    if not data:
        raise SystemExit("empty payload")

    with open(OUT, "w") as f:
        f.write("// GENERATED by tools/gen_selftest_py.py from tests/selftest.S -- do not edit.\n")
        f.write('#include "SelfTest.h"\n\n')
        f.write("static const uint8_t kProgram[] = {")
        for i in range(0, len(data), 12):
            f.write("\n    " + ", ".join("0x%02x" % b for b in data[i:i+12]) + ",")
        f.write("\n};\n\n")
        f.write("const uint8_t *lopSelfTestProgram(size_t *len) {\n    *len = sizeof kProgram;\n    return kProgram;\n}\n\n")
        f.write('const char *lopSelfTestExpected() {\n    return "Hello from the ARM64 guest!\\n6*7=42\\nfib(20)=6765\\n";\n}\n')
    print(f"wrote {OUT}")

    if "--disasm" in sys.argv:
        for addr, size, mn, ops in dis:
            print(f"{addr:08x}: {mn:8s} {ops}")

if __name__ == "__main__":
    main()
