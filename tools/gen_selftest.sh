#!/bin/sh
# Regenerates Engine/SelfTest.cpp from tests/selftest.S.
# Needs aarch64-linux-gnu-as / -ld / -objcopy (Ubuntu: apt install binutils-aarch64-linux-gnu).
set -e
cd "$(dirname "$0")/.."
TMP=$(mktemp -d)
aarch64-linux-gnu-as -o "$TMP/s.o" tests/selftest.S
aarch64-linux-gnu-ld -Ttext=0x40000000 -o "$TMP/s.elf" "$TMP/s.o"
aarch64-linux-gnu-objcopy -O binary "$TMP/s.elf" "$TMP/s.bin"
python3 - "$TMP/s.bin" > Engine/SelfTest.cpp <<'PY'
import sys
d = open(sys.argv[1], 'rb').read()
print("// GENERATED by tools/gen_selftest.sh from tests/selftest.S -- do not edit.")
print('#include "SelfTest.h"\n')
print("static const uint8_t kProgram[] = {")
for i in range(0, len(d), 12):
    print("    " + ", ".join("0x%02x" % b for b in d[i:i+12]) + ",")
print("};\n")
print("const uint8_t *lopSelfTestProgram(size_t *len) {\n    *len = sizeof kProgram;\n    return kProgram;\n}\n")
print('const char *lopSelfTestExpected() {\n    return "Hello from the ARM64 guest!\\n6*7=42\\nfib(20)=6765\\n";\n}')
PY
rm -rf "$TMP"
echo "wrote Engine/SelfTest.cpp"
